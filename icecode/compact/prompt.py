"""Full compact 摘要提示词（TEXT ONLY，不使用工具）。"""

from __future__ import annotations


def build_compact_system_prompt() -> str:
    """摘要调用的 system prompt：只输出纯文本结构化摘要。"""
    return """\
你是负责压缩对话的助手。只输出纯文本摘要，禁止调用任何工具。

根据上方完整对话，写一份足够让后续助手无缝继续工作的详细摘要，必须包含以下小节：

1. 用户的主要请求与意图
2. 关键技术概念、技术栈与架构决策
3. 涉及的文件与代码（路径、为何重要、重要片段或改动）
4. 遇到的错误与修复方式（含用户纠正）
5. 已解决的问题与仍在排查的事项
6. 所有非工具结果的用户原文要点
7. 尚未完成的待办
8. 压缩前正在做的工作（尽量具体到文件与位置）
9. 建议的下一步（必须紧贴用户最近的明确请求；若任务已结束则不要编造新任务）

要求：
- 只输出最终摘要正文，不要工具调用，不要分析草稿标签，不要开场白。
- 保留精确的文件名、函数名、命令与关键代码。
- 用简洁中文；专有名词与代码保持原样。
"""


def build_compact_user_message(summary: str, transcript_path: str | None) -> str:
    """把摘要包装成继续对话用的 user 文本。"""
    text = (
        "本会话因上下文过长已压缩。以下摘要覆盖此前对话，"
        "请从中断处直接继续，不要复述摘要，不要问候，不要确认「我将继续」。\n\n"
        f"{summary.strip()}"
    )
    if transcript_path:
        text += (
            "\n\n如需压缩前的具体细节（完整代码、报错原文等），"
            f"可读取完整记录：{transcript_path}"
        )
    return text
